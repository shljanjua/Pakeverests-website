<p>A clean, dry, covered space away from direct sunlight, heat, and any chemical, fuel or paint. This is a food product and storage discipline is not optional. Storage also has to be secure, because bottle stock is the second largest asset in the business after the vehicle.</p>
<h3>Working capital</h3>
<p>Opening stock, the security deposit under the distributor agreement, fuel, and enough cash to carry credit customers for a month. Underestimating the last of these is the most common reason new distributors run into trouble.</p>
<h3>A rider or two</h3>
<p>Delivery staff are the face of the business. Customers judge the brand entirely by the person at the door.</p>

<h2>The daily work, honestly described</h2>
<p>Morning route loading. Deliveries from roughly 8 AM. Bottle collection alongside every delivery. Cash settlement at each door. Afternoon route for the second half of the territory. Evening reconciliation of cash, stock and empty bottles. New account calls fitted around the route.</p>
<p>The hardest part is not the delivering. It is the reconciliation, every single day, without exception. Distributors who let bottle counts and cash drift for a week are the ones who discover a hole they cannot explain.</p>

<h2>Where the money is made</h2>
<h3>Route density</h3>
<p>Twenty deliveries within two kilometres beats twenty deliveries spread across fifteen. Build a territory outward from a dense core rather than chasing scattered accounts across the map.</p>
<h3>Institutional accounts</h3>
<p>One school, hospital, factory or office block can equal thirty households in volume, on a single stop, with a single payment. These accounts take longer to win and are worth the effort.</p>
<h3>Standing orders</h3>
<p>A fixed weekly schedule lets you plan the route, the stock and the vehicle. One off orders are the least profitable work you will do.</p>
<h3>Bottle discipline</h3>
<p>Every uncontrolled bottle is dead capital. Distributors who track bottles by customer keep their working capital working.</p>

<h2>The four mistakes that sink new distributors</h2>
<ol>
<li><strong>Uncontrolled credit.</strong> Extending credit to win accounts, then finding a month of sales sitting in other people pockets. Set a limit per customer and hold it.</li>
<li><strong>Poor bottle tracking.</strong> Bottles issued and never recorded. By month six nobody knows where a hundred bottles went.</li>
<li><strong>Over promising delivery times.</strong> Promising a slot you cannot hold in summer loses accounts permanently. Under promise.</li>
<li><strong>Neglecting storage hygiene.</strong> One contaminated batch, one complaint to the food authority, and the territory reputation takes a year to rebuild.</li>
</ol>

